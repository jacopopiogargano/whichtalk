const iconTemplates = new Map()
function iconTemplate (name) {
  let tpl = iconTemplates.get(name)
  if (!tpl) {
    tpl = h('span', { class: 'icon', 'aria-hidden': 'true' })
    tpl.innerHTML = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${ICON_PATHS[name] || ''}</svg>`
    iconTemplates.set(name, tpl)
  }
  return tpl
}

export function icon (name, extraClass) {
  const node = iconTemplate(name).cloneNode(true)
  if (extraClass) node.classList.add(extraClass)
  return node
}
